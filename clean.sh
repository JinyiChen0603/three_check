#!/bin/bash

# =============================================================================
# MathTasks 项目清理脚本
# =============================================================================
# 用途：完全清理项目（停止服务、删除容器、清理数据）
# 警告：此操作会删除所有数据库数据！
# 使用方法：./clean.sh
# =============================================================================

echo "=========================================="
echo "⚠️  MathTasks 项目清理"
echo "=========================================="
echo ""
echo "⚠️  警告：此操作将："
echo "  1. 停止所有服务"
echo "  2. 删除所有 Docker 容器"
echo "  3. 删除数据库数据卷"
echo "  4. 清理日志文件"
echo ""
read -p "确认要继续吗？(yes/no): " CONFIRM

if [ "$CONFIRM" != "yes" ]; then
    echo ""
    echo "❌ 已取消清理操作"
    exit 0
fi

echo ""

# =============================================================================
# 1. 停止服务
# =============================================================================
echo "步骤 1/4: 停止所有服务..."
./stop.sh > /dev/null 2>&1 || true

echo ""

# =============================================================================
# 2. 删除 Docker 容器和网络
# =============================================================================
echo "步骤 2/4: 删除 Docker 容器..."

cd backend
docker compose down
echo "✅ 容器已删除"

echo ""

# =============================================================================
# 3. 删除数据卷（可选）
# =============================================================================
echo "步骤 3/4: 删除数据库数据..."
read -p "是否删除数据库数据卷？(yes/no): " DELETE_VOLUMES

if [ "$DELETE_VOLUMES" = "yes" ]; then
    docker compose down -v
    echo "✅ 数据卷已删除"
else
    echo "✅ 保留数据卷"
fi

cd ..

echo ""

# =============================================================================
# 4. 清理日志
# =============================================================================
echo "步骤 4/4: 清理日志文件..."

if [ -d "logs" ]; then
    rm -rf logs/*
    echo "✅ 日志已清理"
else
    echo "✅ 无日志需要清理"
fi

echo ""

# =============================================================================
# 完成
# =============================================================================
echo "=========================================="
echo "✅ 清理完成"
echo "=========================================="
echo ""
echo "💡 下一步："
echo "  - 重新初始化: ./setup.sh"
echo "  - 启动服务: ./start.sh"
echo ""

