#!/bin/bash

# =============================================================================
# MathTasks 项目停止脚本
# =============================================================================
# 用途：停止所有服务
# 使用方法：./stop.sh
# =============================================================================

echo "=========================================="
echo "🛑 停止 MathTasks 项目"
echo "=========================================="
echo ""

# =============================================================================
# 1. 停止前端
# =============================================================================
echo "步骤 1/2: 停止前端服务..."

if lsof -ti:5173 > /dev/null 2>&1; then
    echo "正在停止前端..."
    kill $(lsof -ti:5173) 2>/dev/null || true
    pkill -f "vite" 2>/dev/null || true
    echo "✅ 前端已停止"
else
    echo "✅ 前端未运行"
fi

echo ""

# =============================================================================
# 2. 停止后端和数据库
# =============================================================================
echo "步骤 2/2: 停止后端和数据库..."

cd backend

if docker compose ps | grep -q "Up"; then
    echo "正在停止 Docker 容器..."
    docker compose stop
    echo "✅ Docker 容器已停止"
else
    echo "✅ Docker 容器未运行"
fi

cd ..

echo ""
echo "=========================================="
echo "✅ 所有服务已停止"
echo "=========================================="
echo ""
echo "💡 提示："
echo "  - 重新启动: ./start.sh"
echo "  - 完全清理: ./clean.sh"
echo ""

