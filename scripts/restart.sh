#!/bin/bash

# =============================================================================
# MathTasks 项目重启脚本
# =============================================================================
# 用途：重启所有服务
# 使用方法：./scripts/restart.sh
# =============================================================================

echo "=========================================="
echo "🔄 重启 MathTasks 项目"
echo "=========================================="
echo ""

# 停止服务
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
"$ROOT_DIR/scripts/stop.sh"

echo ""
echo "⏳ 等待服务完全停止..."
sleep 3
echo ""

# 启动服务
"$ROOT_DIR/scripts/start.sh"

